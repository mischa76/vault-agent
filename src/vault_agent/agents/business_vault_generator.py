"""Business Vault generation (WP91, ADR-0016): a point-in-time table per hub, in our own SQL.

AutomateDV 0.11.4 deprecates its ``pit()`` and ``bridge()`` macros („not currently
fit-for-purpose");
ADR-0016 (option B) lets this module render the Business Vault constructs itself, as a scoped
exception to the rule that the generated vault is AutomateDV's. Everything else stays AutomateDV's,
and the ghost values a PIT writes are AutomateDV's own helpers (``binary_ghost``, ``date_ghost``),
so they equal the ghost records the satellites carry when ``enable_ghost_records`` is on.

Deterministic, no prompt: it reads the model and the raw-vault metadata the code generator has
just produced — the one place a hub's and a satellite's hash-key and load-date columns are decided.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from vault_agent.rules.dv2_rules import construct_base_name
from vault_agent.state import BusinessVaultOptions, DVModel, FlagKind, Hub, PipelineFlag, Satellite

AS_OF_MODEL = "as_of_dates"
# A hub's descriptive payload: standard and multi-active satellites. An effectivity satellite
# describes a relationship's validity, not the hub; link satellites belong to the link.
DESCRIPTIVE_SAT_TYPES = ("standard", "multi_active")


@dataclass
class BusinessVaultResult:
    models: dict[str, str] = field(default_factory=dict)
    metadata: dict[str, dict[str, Any]] = field(default_factory=dict)
    flags: list[PipelineFlag] = field(default_factory=list)


def pit_model_name(hub: Hub) -> str:
    return "pit_" + construct_base_name(hub.name)


def pit_hubs(model: DVModel) -> dict[str, list[Satellite]]:
    """The hubs that get a PIT: two or more descriptive satellites whose parent is the hub."""
    by_parent: dict[str, list[Satellite]] = {}
    for sat in model.satellites:
        if sat.sat_type in DESCRIPTIVE_SAT_TYPES:
            by_parent.setdefault(sat.parent, []).append(sat)
    return {
        hub.name: by_parent[hub.name]
        for hub in model.hubs
        if len(by_parent.get(hub.name, [])) >= 2
    }


def render_as_of_dates(options: BusinessVaultOptions) -> str:
    start, end, grain = options.as_of_start, options.as_of_end, options.as_of_grain
    return (
        "{{ config(materialized='table') }}\n"
        "-- Generated by vault-agent (WP91, ADR-0016): the as-of spine every PIT of this project\n"
        f"-- reads — one row per {grain} from {start} (inclusive) to {end} (exclusive), the\n"
        "-- operator's bounds (`--as-of-start`, `--as-of-end`, `--as-of-grain`).\n"
        f"select cast(date_{grain} as timestamp) as AS_OF_DATE\n"
        "from (\n"
        f"    {{{{ dbt_utils.date_spine(datepart=\"{grain}\", "
        f"start_date=\"cast('{start}' as date)\", end_date=\"cast('{end}' as date)\") }}}}\n"
        ") spine\n"
    )


def render_pit(
    hub: Hub, src_pk: str, satellites: list[tuple[str, str, str]], multi_active: list[str]
) -> str:
    """The PIT model: ``satellites`` is ``(model name, key column, load-date column)`` per
    rendered satellite model, in model order; ``multi_active`` names those without a ghost
    record."""
    name = pit_model_name(hub)
    lines = [
        f"-- Generated by vault-agent (WP91, ADR-0016): point-in-time table for {hub.name}.",
        "-- One row per hub key and as-of date; per satellite the key and load date of its",
        "-- latest row at or before the as-of date. A missing row is AutomateDV's ghost record",
        "-- (the project enables ghost records), so a join on (<SAT>_PK, <SAT>_LDTS) finds a row",
        "-- for every entry of a standard satellite.",
    ]
    if multi_active:
        lines += [
            "-- AutomateDV 0.11.4 has no ghost record for a multi-active satellite: a ghost",
            f"-- entry of {', '.join(multi_active)} joins nothing — join those LEFT.",
        ]
    lines += [
        "{{ config(materialized='table') }}",
        "",
        "with as_of as (",
        f"    select AS_OF_DATE from {{{{ ref('{AS_OF_MODEL}') }}}}",
        "),",
        "base as (",
        f"    select h.{src_pk}, a.AS_OF_DATE",
        f"    from {{{{ ref('{hub.name}') }}}} h cross join as_of a",
        ")",
    ]
    for sat, pk, ldts in satellites:
        lines += [
            ",",
            f"{sat}_latest as (",
            f"    select b.{src_pk}, b.AS_OF_DATE, max(s.{ldts}) as LDTS",
            "    from base b",
            f"    left join {{{{ ref('{sat}') }}}} s",
            f"      on s.{pk} = b.{src_pk} and s.{ldts} <= b.AS_OF_DATE",
            f"    group by b.{src_pk}, b.AS_OF_DATE",
            ")",
        ]
    lines += ["", f"select b.{src_pk}, b.AS_OF_DATE"]
    for sat, _pk, _ldts in satellites:
        upper = sat.upper()
        lines += [
            f"    , case when {sat}_latest.LDTS is null",
            "           then {{ automate_dv.binary_ghost(none, var('hash', 'MD5')) }}",
            f"           else b.{src_pk} end as {upper}_PK",
            f"    , coalesce({sat}_latest.LDTS, "
            f"{{{{ automate_dv.date_ghost(date_type='timestamp') }}}}) as {upper}_LDTS",
        ]
    lines += ["from base b"]
    for sat, _pk, _ldts in satellites:
        lines += [
            f"join {sat}_latest",
            f"  on {sat}_latest.{src_pk} = b.{src_pk} and {sat}_latest.AS_OF_DATE = b.AS_OF_DATE",
        ]
    lines += [f"-- {name}", ""]
    return "\n".join(lines)


def _rendered_satellite_models(
    sat: Satellite, raw_metadata: dict[str, Any], src_pk: str
) -> list[tuple[str, str, str]]:
    """The raw-vault models a satellite became — its own name, or per-source names on a
    multi-source hub (WP10) — keyed on the hub's hash key. A satellite the generator could not
    render (a flagged generation gap) has none and is left out."""
    found = []
    for model_name, meta in raw_metadata.get("satellites", {}).items():
        if model_name != sat.name and not model_name.startswith(sat.name + "_"):
            continue
        if meta.get("src_pk") != src_pk:
            continue
        found.append((model_name, str(meta["src_pk"]), str(meta.get("src_ldts", "LOAD_DATETIME"))))
    return found


def build_business_vault(
    model: DVModel, raw_metadata: dict[str, Any], options: BusinessVaultOptions
) -> BusinessVaultResult:
    """Every PIT the options ask for; empty — and nothing else changed — when they do not."""
    result = BusinessVaultResult()
    if not options.pit:
        return result
    eligible = pit_hubs(model)
    for hub in model.hubs:
        sats = eligible.get(hub.name)
        if not sats:
            continue
        hub_meta = raw_metadata.get("hubs", {}).get(hub.name)
        if hub_meta is None:
            continue
        src_pk = str(hub_meta["src_pk"])
        rendered: list[tuple[str, str, str]] = []
        multi_active: list[str] = []
        for sat in sats:
            models = _rendered_satellite_models(sat, raw_metadata, src_pk)
            rendered.extend(models)
            if sat.sat_type == "multi_active":
                multi_active.extend(m for m, _, _ in models)
        if len(rendered) < 2:
            continue
        name = pit_model_name(hub)
        result.models[name] = render_pit(hub, src_pk, rendered, multi_active)
        result.metadata[name] = {
            "source_model": hub.name,
            "src_pk": src_pk,
            "src_ldts": str(hub_meta.get("src_ldts", "LOAD_DATETIME")),
            "as_of_dates_table": AS_OF_MODEL,
            "satellites": {m: {"pk": pk, "ldts": ldts} for m, pk, ldts in rendered},
        }
        result.flags.append(PipelineFlag(
            agent="code_generator",
            message=(
                f"point-in-time table {name} generated for {hub.name} over "
                f"{len(rendered)} satellite model(s): {', '.join(m for m, _, _ in rendered)}; "
                f"deterministic from the model (ADR-0016), ghost entries are AutomateDV ghost "
                f"records" + (
                    f" — none exist for the multi-active {', '.join(multi_active)}, join those LEFT"
                    if multi_active else ""
                )
            ),
            kind=FlagKind.PIT_GENERATED,
            asset=name,
        ))
    if result.models:
        result.models = {AS_OF_MODEL: render_as_of_dates(options), **result.models}
    return result
