"""Derive the WP30 case assets from the checked-in AdventureWorks extract.

Deterministic and keyless: the same extract yields byte-identical `source_schema.yml` and
`golden_mapping.yml` for every subject area (WP30 §3.4). Nothing here decides anything about
the business — that is the point of the WP, and it is enforced by two rules:

**The schema is transcribed, never curated.** Every table of a subject area is declared, with
every column, its type, and its description VERBATIM where Microsoft wrote one (§2.3 as
amended). A column Microsoft left undescribed is declared without a comment.

**The golden contains ONLY Microsoft's own key declarations.** A business key here is a column
carrying a single-column ``AK_*`` unique index — Microsoft's statement that this is the natural
key of the entity — never a column we picked because it looked like one. Descriptive attributes
are deliberately NOT in the golden: choosing which of 465 columns "should" be modelled is
exactly the modelling opinion this instrument exists to keep out, and `mapping_coverage` would
then measure our taste rather than the mapper.

The consequence is worth stating plainly, because it shapes how the score reads:
`mapping_coverage` on these cases answers one sharp question — **did the mapper find the real
natural-key columns?** — and nothing else.

``rowguid`` columns become **false friends**: they are perfectly unique (Microsoft indexes them
``AK_<table>_rowguid``) and are never a business key. A lexical or profiling-driven matcher is
genuinely tempted by them, which is the GUID-shadow trap `messy_insurance` had to synthesise and
this schema supplies for free.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import yaml

# Audit/technical columns every AdventureWorks table carries. Named here so the derivation is
# explicit about what it treats as non-business, rather than silently filtering.
AUDIT_COLUMNS = ("ModifiedDate", "rowguid")

# Arm B's step order, derived from the extract's foreign keys and RECORDED in the spec (§7.1)
# before any live run, so it can never be chosen after seeing a result. `foreign_key_edges`
# reproduces the derivation; this constant is what the cases actually use.
ARM_B_ORDER = ("Person", "HumanResources", "Production", "Purchasing", "Sales")

_HEADER = (
    "# Derived from the Microsoft AdventureWorks OLTP sample database (MIT) —\n"
    "# see NOTICE. Generated by eval.adventureworks.derive; do not edit by hand.\n"
    "# Descriptions are VERBATIM from the upstream DDL (WP30 section 2.3).\n"
)


def subject_areas(extract: dict[str, Any]) -> list[str]:
    return list(extract["schemas"])


def tables_of(extract: dict[str, Any], schema: str) -> list[dict[str, Any]]:
    return [t for t in extract["tables"] if t["schema"] == schema]


def _natural_keys(table: dict[str, Any]) -> list[str]:
    """Microsoft's single-column ``AK_*`` natural keys, technical GUIDs excluded.

    Composite alternate keys are deliberately skipped: a multi-column natural key maps to
    several (table, column) pairs whose individual binding says nothing about whether the
    mapper understood the key, so scoring them as separate pairs would be noise."""
    return [
        ak["columns"][0]
        for ak in table["alternate_keys"]
        if not ak["technical_guid"] and len(ak["columns"]) == 1
    ]


def build_source_schema(extract: dict[str, Any], schema: str) -> dict[str, Any]:
    """One declared source table per table of the subject area (ADR-0004 / WP9 §3.1 shape)."""
    tables = []
    for table in tables_of(extract, schema):
        columns = []
        for col in table["columns"]:
            entry: dict[str, Any] = {"name": col["name"], "type": col["type"]}
            if col["description"]:
                entry["comment"] = col["description"]
            columns.append(entry)
        declared: dict[str, Any] = {
            "table": table["name"],
            "schema": table["schema"],
            "columns": columns,
        }
        # WP34 §3.1: the foreign keys extract.py already parses, which this function used to
        # drop. They were never visible to any agent, which is what WP30.1-30.3 spent ~$46
        # discovering the hard way. Emitted only when the table declares some, so a table
        # without them stays byte-identical to the pre-WP34 derivation.
        if table["foreign_keys"]:
            declared["foreign_keys"] = [
                {
                    "columns": list(fk["columns"]),
                    "references_table": fk["references_table"],
                    "references_columns": list(fk["references_columns"]),
                    "references_schema": fk["references_schema"],
                }
                for fk in table["foreign_keys"]
            ]
        tables.append(declared)
    return {"source_schemas": tables}


def build_golden_mapping(extract: dict[str, Any], schema: str) -> dict[str, Any]:
    """Microsoft's declared natural keys as the golden; ``rowguid`` as the false friend."""
    mappings: list[dict[str, Any]] = []
    false_friends: list[dict[str, Any]] = []

    for table in tables_of(extract, schema):
        for column in _natural_keys(table):
            mappings.append({
                # Presentational only: in WP14 column mode the scorers match on the
                # (source_table, source_column) PAIR, never on this label.
                "concept": f"{table['name']} {column}",
                "entity": table["name"],
                "source_table": table["name"],
                "source_column": column,
                "kind": "business_key",
            })
        if any(ak["technical_guid"] for ak in table["alternate_keys"]):
            false_friends.append({
                "table": table["name"],
                "column": "rowguid",
                "note": (
                    "technical row GUID — perfectly unique and indexed as a unique key, but "
                    "never a business key"
                ),
            })

    return {"mappings": mappings, "false_friends": false_friends}


def _dump(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        _HEADER + yaml.safe_dump(payload, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )


def case_dir_name(schema: str) -> str:
    """`HumanResources` -> `adventureworks_humanresources` (a case name, lowercase)."""
    return f"adventureworks_{schema.lower()}"


def derive_all(extract: dict[str, Any], out_root: Path) -> dict[str, dict[str, int]]:
    """Write every subject area's assets; returns per-area counts for the console summary."""
    summary: dict[str, dict[str, int]] = {}
    for schema in subject_areas(extract):
        case_dir = out_root / case_dir_name(schema)
        source_schema = build_source_schema(extract, schema)
        golden = build_golden_mapping(extract, schema)
        _dump(case_dir / "source_schema.yml", source_schema)
        _dump(case_dir / "golden_mapping.yml", golden)
        summary[schema] = {
            "tables": len(source_schema["source_schemas"]),
            "columns": sum(len(t["columns"]) for t in source_schema["source_schemas"]),
            "described": sum(
                1
                for t in source_schema["source_schemas"]
                for c in t["columns"]
                if "comment" in c
            ),
            "natural_keys": len(golden["mappings"]),
            "false_friends": len(golden["false_friends"]),
        }
    return summary


def build_combined_source_schema(extract: dict[str, Any]) -> dict[str, Any]:
    """Arm A's declared schema: every subject area at once, in the recorded step order."""
    tables: list[dict[str, Any]] = []
    for schema in ARM_B_ORDER:
        tables.extend(build_source_schema(extract, schema)["source_schemas"])
    return {"source_schemas": tables}


def build_combined_golden(extract: dict[str, Any]) -> dict[str, Any]:
    """Arm A's golden: the union of the per-area goldens. Same entries, one file."""
    mappings: list[dict[str, Any]] = []
    false_friends: list[dict[str, Any]] = []
    for schema in ARM_B_ORDER:
        golden = build_golden_mapping(extract, schema)
        mappings.extend(golden["mappings"])
        false_friends.extend(golden["false_friends"])
    return {"mappings": mappings, "false_friends": false_friends}


def combine_requirements(out_root: Path) -> str:
    """Arm A's document: the five blinded documents concatenated, unedited.

    Deliberately NOT rewritten into one coherent narrative. Editing them would (a) undo the
    §2.4a blinding, since the editor sees all five and the rest of the project, and (b) make
    the two arms differ in their INPUT as well as their method, which would confound the
    comparison the WP exists to run. Arm A gets exactly the text arm B gets, all at once."""
    parts = []
    for schema in ARM_B_ORDER:
        path = out_root / case_dir_name(schema) / "requirements.md"
        parts.append(f"# Subject area: {schema}\n\n{path.read_text(encoding='utf-8').strip()}")
    return "\n\n---\n\n".join(parts) + "\n"


def foreign_key_edges(extract: dict[str, Any]) -> dict[str, set[str]]:
    """Cross-subject-area FK edges: schema -> the schemas it references (itself excluded).

    Arm B's step order is derived from this and recorded in the spec BEFORE the first run, so
    the order is never chosen after seeing a result (WP30 §2.4)."""
    edges: dict[str, set[str]] = {s: set() for s in subject_areas(extract)}
    for table in extract["tables"]:
        for fk in table["foreign_keys"]:
            target = fk["references_schema"]
            if target != table["schema"] and target in edges:
                edges[table["schema"]].add(target)
    return edges


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--extract", type=Path,
        default=Path("eval/datasets/adventureworks/schema_extract.json"),
    )
    parser.add_argument("--out", type=Path, default=Path("eval/datasets"))
    args = parser.parse_args()

    extract = json.loads(args.extract.read_text(encoding="utf-8"))
    summary = derive_all(extract, args.out)

    # Arm A: the same inputs, undivided.
    full = args.out / "adventureworks_full"
    _dump(full / "source_schema.yml", build_combined_source_schema(extract))
    _dump(full / "golden_mapping.yml", build_combined_golden(extract))
    (full / "requirements.md").write_text(combine_requirements(args.out), encoding="utf-8")

    print(f"{'subject area':16} {'tables':>7} {'columns':>8} {'described':>10} "
          f"{'nat.keys':>9} {'false fr.':>10}")
    for schema, counts in summary.items():
        print(f"{schema:16} {counts['tables']:>7} {counts['columns']:>8} "
              f"{counts['described']:>10} {counts['natural_keys']:>9} "
              f"{counts['false_friends']:>10}")

    print("\ncross-subject-area FK references (arm B ordering input):")
    for schema, targets in foreign_key_edges(extract).items():
        print(f"  {schema:16} -> {', '.join(sorted(targets)) or '(none)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
